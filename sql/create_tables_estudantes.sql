/*Apaga as tabelas, das filhas para as pais*/
DROP TABLE NOTAS;
DROP TABLE ALUNOS;
DROP TABLE DISCIPLINAS;
DROP TABLE CURSOS;

/*Apaga as sequences*/
DROP SEQUENCE CURSOS_ID_CURSO_SEQ;
DROP SEQUENCE DISCIPLINAS_ID_DISCIPLINA_SEQ;
DROP SEQUENCE NOTAS_ID_NOTA_SEQ;

/*Cria as tabelas*/


CREATE TABLE CURSOS (
  ID_CURSO NUMBER       NOT NULL,
  NOME      VARCHAR2(100) NOT NULL,
  DURACAO_SEMESTRES   NUMBER       NOT NULL,
  CONSTRAINT CURSOS_PK PRIMARY KEY (ID_CURSO)
);

CREATE TABLE DISCIPLINAS (
  ID_DISCIPLINA NUMBER        NOT NULL,
  NOME          VARCHAR2(100) NOT NULL,
  CARGA_HORARIA NUMBER        NOT NULL,
  ID_CURSO      NUMBER        NOT NULL,
  CONSTRAINT  DISCIPLINAS_PK  PRIMARY KEY (ID_DISCIPLINA)
  );

CREATE TABLE ALUNOS (
  MATRICULA VARCHAR2(15)  NOT NULL,
  NOME      VARCHAR2(100) NOT NULL,
  ID_CURSO  NUMBER        NOT NULL,
  CONSTRAINT ALUNOS_PK    PRIMARY KEY (MATRICULA)
);

CREATE TABLE NOTAS (
  ID_NOTA         NUMBER       NOT NULL,
  MATRICULA       VARCHAR2(15) NOT NULL,
  ID_DISCIPLINA   NUMBER       NOT NULL,
  SEMESTRE        VARCHAR2(6) NOT NULL,
  ATIVIDADE       VARCHAR2(50) NOT NULL, 
  NOTA            NUMBER(4,2)     NOT NULL,
  CONSTRAINT NOTAS_NOTA_CK CHECK (NOTA BETWEEN 0 AND 10),
  CONSTRAINT NOTAS_PK          PRIMARY KEY (ID_NOTA)
);

CREATE SEQUENCE CURSOS_ID_CURSO_SEQ;
CREATE SEQUENCE DISCIPLINAS_ID_DISCIPLINA_SEQ;
CREATE SEQUENCE NOTAS_ID_NOTA_SEQ;

ALTER TABLE DISCIPLINAS ADD CONSTRAINT CURSOS_DISCIPLINAS_FK 
FOREIGN KEY (ID_CURSO)
REFERENCES CURSOS (ID_CURSO)
NOT DEFERRABLE;

ALTER TABLE ALUNOS ADD CONSTRAINT CURSOS_ALUNOS_FK 
FOREIGN KEY (ID_CURSO)
REFERENCES CURSOS (ID_CURSO)
NOT DEFERRABLE;

ALTER TABLE NOTAS ADD CONSTRAINT ALUNOS_NOTAS_FK 
FOREIGN KEY (MATRICULA)
REFERENCES ALUNOS (MATRICULA)
NOT DEFERRABLE;

ALTER TABLE NOTAS ADD CONSTRAINT DISCIPLINAS_NOTAS_FK
FOREIGN KEY (ID_DISCIPLINA)
REFERENCES DISCIPLINAS (ID_DISCIPLINA)
NOT DEFERRABLE;




